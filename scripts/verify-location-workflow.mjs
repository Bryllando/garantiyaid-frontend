import assert from 'node:assert/strict'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { chromium, expect } from '@playwright/test'
import { createServer } from 'vite'
import { env } from '../../garantiyaid-backend/src/config/env.js'

export async function runLocationJourney({ staff, baseUrl, output, check, locations, person, missing, enrollment, secondEnrollment, otherProgram, event, nextEvent, unrelatedEvent, outsideEvent, receipt, createEvent, post }) {
  const root = fileURLToPath(new URL('..', import.meta.url))
  const vite = await createServer({ root, configFile: resolve(root, 'vite.config.js'), cacheDir: resolve(output, '../../tmp/location-workflow-vite'), server: { host: '127.0.0.1', port: 0, strictPort: false, proxy: { '/api/v1': { target: baseUrl, changeOrigin: true }, '/socket.io': { target: baseUrl, changeOrigin: true, ws: true } } } })
  await vite.listen()
  const origin = `http://127.0.0.1:${vite.httpServer.address().port}`
  env.corsOrigins.push(origin)
  let browser, page
  try {
    browser = await chromium.launch({ channel: 'chrome', headless: true })
    page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    page.setDefaultTimeout(15000)
    const errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(origin)
    async function as(role, path = '/beneficiaries') {
      await page.evaluate(session => { sessionStorage.setItem('garantiyaid.accessToken', session.accessToken); sessionStorage.setItem('garantiyaid.user', JSON.stringify(session.user)) }, staff[role])
      await page.goto(origin + path)
    }
    const [north, south, otherCity] = locations
    await as('admin')
    await page.getByRole('button', { name: 'Register beneficiary', exact: true }).click()
    let form = page.getByRole('dialog')
    await form.getByLabel('City', { exact: true }).selectOption(north.city)
    await form.getByLabel('Barangay', { exact: true }).selectOption(north.barangayId)
    await form.getByLabel('Sitio / Purok', { exact: true }).selectOption('Purok North')
    await form.getByLabel('City', { exact: true }).selectOption(otherCity.city)
    await expect(form.getByLabel('Barangay', { exact: true }).locator('option')).toHaveCount(2)
    await form.getByLabel('Barangay', { exact: true }).selectOption(otherCity.barangayId)
    await expect(form.getByLabel('Sitio / Purok', { exact: true })).toHaveValue('')
    assert.equal(await form.getByLabel('Sitio / Purok', { exact: true }).evaluate(node => node.checkValidity()), false)
    await expect(form.getByText(/Review the previous location/)).toContainText('Purok North')
    await form.getByLabel('Sitio / Purok', { exact: true }).selectOption('__review__')
    await expect(form.getByLabel('Unconfirmed Sitio / Purok')).toHaveValue('Purok North')
    await form.getByLabel('Sitio / Purok', { exact: true }).selectOption('Sitio Riverside')
    await form.getByLabel('City', { exact: true }).selectOption(north.city)
    await form.getByLabel('Barangay', { exact: true }).selectOption(south.barangayId)
    await expect(form.getByLabel('Sitio / Purok', { exact: true })).toHaveValue('')
    await form.getByLabel('Sitio / Purok', { exact: true }).selectOption('Sitio Riverside')
    await page.screenshot({ path: resolve(output, 'admin-location-fields.png') })
    await page.keyboard.press('Escape')
    check('Admin City filters Barangays; a parent change requires explicit review while retaining the previous Sitio text')

    await as('barangay')
    await page.getByRole('button', { name: 'Register beneficiary', exact: true }).click()
    form = page.getByRole('dialog')
    await expect(form.getByLabel('City', { exact: true })).toBeDisabled()
    await expect(form.getByLabel('Barangay', { exact: true })).toBeDisabled()
    await expect(form.getByLabel('Barangay', { exact: true })).toHaveValue(north.barangayId)
    await expect(form.getByLabel('Sitio / Purok', { exact: true }).locator('option[value="Purok North"]')).toBeAttached()
    assert.ok(!(await form.getByLabel('Sitio / Purok', { exact: true }).locator('option').allTextContents()).includes('Purok South'))
    await page.setViewportSize({ width: 390, height: 900 })
    await form.getByLabel('City', { exact: true }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: resolve(output, 'barangay-location-fields-390.png') })
    assert.equal(await form.evaluate(node => node.scrollWidth <= node.clientWidth), true)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.keyboard.press('Escape')
    check('Barangay form locks the assigned parent and offers only its areas; mobile layout has no horizontal overflow')

    await page.setViewportSize({ width: 1440, height: 1000 })
    await as('admin', `/beneficiaries?beneficiary=${person.beneficiaryId}`)
    const hierarchy = page.getByRole('region', { name: 'Location hierarchy' })
    await expect(hierarchy).toContainText(north.city)
    await expect(hierarchy).toContainText(north.barangayName)
    await expect(hierarchy).toContainText('Sitio Riverside')
    const progress = page.getByRole('region', { name: 'Assistance progress' })
    await progress.getByLabel('Program enrollment', { exact: true }).selectOption(enrollment.enrollmentId)
    const eventSelect = progress.getByLabel('Distribution event', { exact: true })
    await expect(eventSelect.locator(`option[value="${event.distributionId}"]`)).toContainText(`Barangay ${north.barangayName}`)
    await expect(eventSelect.locator(`option[value="${unrelatedEvent.distributionId}"]`)).toHaveCount(0)
    await expect(eventSelect.locator(`option[value="${outsideEvent.distributionId}"]`)).toHaveCount(0)
    await eventSelect.selectOption(event.distributionId)
    await expect(progress).toContainText(receipt.receiptNo)
    await eventSelect.selectOption(nextEvent.distributionId)
    await expect(progress.getByRole('list', { name: 'Beneficiary assistance stages' })).toBeVisible()
    await expect(progress).not.toContainText(receipt.receiptNo)
    await expect(progress).toContainText('Available after release')
    await expect(progress).toContainText('Assigned')
    const fresh = await createEvent('Created while progress is open')
    await expect(eventSelect.locator(`option[value="${fresh.distributionId}"]`)).toHaveCount(0)
    await progress.getByRole('button', { name: 'Refresh progress' }).click()
    await expect(eventSelect.locator(`option[value="${fresh.distributionId}"]`)).toBeAttached()
    await eventSelect.selectOption(fresh.distributionId)
    await expect(progress).toContainText('Not assigned to this event')
    await expect(progress).not.toContainText(receipt.receiptNo)
    check('Event choices show the actual Barangay; refresh finds a new event and its empty progress without reusing the original receipt')

    await page.route('**/api/v1/distributions/*/claims?*', async route => { await new Promise(done => setTimeout(done, 350)); await route.continue().catch(() => {}) })
    await eventSelect.selectOption(event.distributionId)
    await eventSelect.selectOption(nextEvent.distributionId)
    await expect(progress).toContainText('Available after release')
    await progress.getByLabel('Program enrollment', { exact: true }).selectOption(secondEnrollment.enrollmentId)
    await expect(eventSelect.locator(`option[value="${unrelatedEvent.distributionId}"]`)).toBeAttached()
    await expect(eventSelect.locator(`option[value="${event.distributionId}"]`)).toHaveCount(0)
    await eventSelect.selectOption(unrelatedEvent.distributionId)
    await expect(progress).toContainText('Not assigned to this event')
    await expect(progress).not.toContainText(receipt.receiptNo)
    await as('admin', `/beneficiaries?beneficiary=${person.beneficiaryId}`)
    await page.getByLabel('Program enrollment', { exact: true }).selectOption(enrollment.enrollmentId)
    await page.getByLabel('Distribution event', { exact: true }).selectOption(event.distributionId)
    await page.getByRole('button', { name: /^MissingArea Location/ }).click()
    await page.getByRole('button', { name: /^Riverside Location/ }).click()
    await page.getByRole('button', { name: /^MissingArea Location/ }).click()
    await page.getByLabel('Distribution event', { exact: true }).selectOption(nextEvent.distributionId)
    await expect(page.getByRole('region', { name: 'Assistance progress' })).toContainText('Available after release')
    await expect(page.getByRole('region', { name: 'Assistance progress' })).not.toContainText(receipt.receiptNo)
    await expect(page.getByRole('region', { name: 'Location hierarchy' })).toContainText('Not recorded')
    await page.screenshot({ path: resolve(output, 'event-progress-isolation.png'), fullPage: true })
    check('Rapid event, program and beneficiary switching ignores delayed old results and preserves the selected person/event context')

    const newEnrollment = (await post('barangay', `/programs/${otherProgram.programId}/enrollments`, { beneficiaryId: missing.beneficiaryId }, { status: 201 })).data.enrollment
    await progress.getByRole('button', { name: 'Refresh progress' }).click()
    await expect(progress.getByLabel('Program enrollment').locator(`option[value="${newEnrollment.enrollmentId}"]`)).toContainText('pending')
    await post('dswd', `/enrollments/${newEnrollment.enrollmentId}/start-review`)
    await post('dswd', `/enrollments/${newEnrollment.enrollmentId}/approve`)
    await expect(progress.getByRole('button', { name: 'Refresh progress' })).toBeEnabled()
    await progress.getByRole('button', { name: 'Refresh progress' }).click()
    await expect(progress.getByLabel('Program enrollment').locator(`option[value="${newEnrollment.enrollmentId}"]`)).toContainText('approved')
    check('Refresh progress finds a newly submitted enrollment and then its actual approved status without another person’s records')

    await as('admin', `/distributions/manage?event=${fresh.distributionId}&stage=sessions`)
    await page.getByRole('radio', { name: 'By Sitio / Purok', exact: true }).check()
    await expect(page.getByText(/eligible beneficiary needs a Sitio\/Purok/)).toBeVisible()
    await page.getByRole('button', { name: 'Generate 1 session', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('Update the Sitio/Purok')
    await page.screenshot({ path: resolve(output, 'missing-sitio-guidance.png'), fullPage: true })
    assert.deepEqual(errors, [])
    check('Area scheduling explains missing Sitio with a correction path; browser journeys complete without React errors')
  } catch (error) {
    await page?.screenshot({ path: resolve(output, 'failure.png'), fullPage: true }).catch(() => {})
    throw error
  } finally { await browser?.close(); await vite.close() }
}
